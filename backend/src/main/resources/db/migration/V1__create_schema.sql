CREATE SEQUENCE SQ_HD_PERSON START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE SQ_HD_TICKET START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE SQ_HD_COMMENT START WITH 1000 INCREMENT BY 1;

CREATE TABLE T_HD_PERSON (
  PK_ID     BIGINT       NOT NULL,
  FULL_NAME VARCHAR(100) NOT NULL,
  EMAIL     VARCHAR(150) NOT NULL,
  ROLE      VARCHAR(20)  NOT NULL,
  CONSTRAINT PK_HD_PERSON PRIMARY KEY (PK_ID),
  CONSTRAINT UK_HD_PERSON_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE T_HD_TICKET (
  PK_ID           BIGINT        NOT NULL,
  TITLE           VARCHAR(120)  NOT NULL,
  DESCRIPTION     VARCHAR(2000) NOT NULL,
  STATUS          VARCHAR(20)   NOT NULL,
  PRIORITY        VARCHAR(20)   NOT NULL,
  CATEGORY        VARCHAR(30)   NOT NULL,
  FK_ID_REQUESTER BIGINT        NOT NULL,
  FK_ID_ASSIGNEE  BIGINT,
  DATE_CREATED    TIMESTAMP     NOT NULL,
  DATE_UPDATED    TIMESTAMP     NOT NULL,
  CONSTRAINT PK_HD_TICKET PRIMARY KEY (PK_ID),
  CONSTRAINT FK_HD_TICKET_REQUESTER FOREIGN KEY (FK_ID_REQUESTER) REFERENCES T_HD_PERSON (PK_ID),
  CONSTRAINT FK_HD_TICKET_ASSIGNEE FOREIGN KEY (FK_ID_ASSIGNEE) REFERENCES T_HD_PERSON (PK_ID)
);

CREATE INDEX IX_HD_TICKET_STATUS ON T_HD_TICKET (STATUS);

CREATE TABLE T_HD_COMMENT (
  PK_ID        BIGINT        NOT NULL,
  FK_ID_TICKET BIGINT        NOT NULL,
  FK_ID_AUTHOR BIGINT        NOT NULL,
  CONTENT      VARCHAR(1000) NOT NULL,
  DATE_CREATED TIMESTAMP     NOT NULL,
  CONSTRAINT PK_HD_COMMENT PRIMARY KEY (PK_ID),
  CONSTRAINT FK_HD_COMMENT_TICKET FOREIGN KEY (FK_ID_TICKET) REFERENCES T_HD_TICKET (PK_ID),
  CONSTRAINT FK_HD_COMMENT_AUTHOR FOREIGN KEY (FK_ID_AUTHOR) REFERENCES T_HD_PERSON (PK_ID)
);

CREATE INDEX IX_HD_COMMENT_TICKET ON T_HD_COMMENT (FK_ID_TICKET);
